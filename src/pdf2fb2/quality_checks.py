"""Sanity checks on segmentation results and on the written FB2 file."""

from collections import Counter
from pathlib import Path

# B405/S405: parses only the FB2 file this program wrote.
from xml.etree import ElementTree  # nosec B405  # noqa: S405

from pdf2fb2.fb2_namespaces import FB2_NAMESPACE, XLINK_NAMESPACE

BOX_TOLERANCE = 2
REPORTED_DUPLICATES = 5


def _check_page_boxes(page_record: dict) -> list[str]:
    """Check one page for missing, degenerate or out-of-page boxes.

    Args:
        page_record: Page record with ``size`` and ``segments``.

    Returns:
        Problem descriptions (empty if the page is fine).
    """
    page_width, page_height = page_record["size"]
    page_number = page_record["page"]
    page_problems = [] if page_record["segments"] else [f"page {page_number}: no segments detected"]
    for page_segment in page_record["segments"]:
        left_edge, top_edge, right_edge, bottom_edge = page_segment["bbox"]
        if not (right_edge > left_edge and bottom_edge > top_edge):
            page_problems.append(f"page {page_number}: degenerate box {page_segment['bbox']}")
        if (left_edge < -BOX_TOLERANCE or top_edge < -BOX_TOLERANCE or right_edge > page_width + BOX_TOLERANCE
                or bottom_edge > page_height + BOX_TOLERANCE):
            page_problems.append(f"page {page_number}: box outside page {page_segment['bbox']}")
    return page_problems


def check_segment_boxes(page_records: list[dict]) -> list[str]:
    """Check all pages' segmentation boxes.

    Args:
        page_records: Page records from the layout stage.

    Returns:
        Problem descriptions for all pages.
    """
    return [page_problem for page_record in page_records for page_problem in _check_page_boxes(page_record)]


def _find_duplicate_ids(element_ids: list[str]) -> list[str]:
    """Report ids used more than once.

    Args:
        element_ids: All ``id`` attribute values.

    Returns:
        At most one problem description.
    """
    duplicate_ids = sorted(element_id for element_id, id_count in Counter(element_ids).items() if id_count > 1)
    return [f"duplicate ids: {duplicate_ids[:REPORTED_DUPLICATES]}"] if duplicate_ids else []


def _find_broken_links(root_element: ElementTree.Element, known_ids: set[str]) -> list[str]:
    """Report internal ``l:href="#id"`` links whose target does not exist.

    Args:
        root_element: Parsed FB2 root.
        known_ids: All ``id`` attribute values.

    Returns:
        One problem per broken link.
    """
    href_attribute = f"{{{XLINK_NAMESPACE}}}href"
    link_targets = (xml_element.get(href_attribute) for xml_element in root_element.iter())
    return [f"broken link {link_target}" for link_target in link_targets
            if link_target and link_target.startswith("#") and link_target[1:] not in known_ids]


def validate_fb2_file(fb2_path: Path) -> list[str]:
    """Validate the written FB2: well-formed XML, unique ids, working links, some paragraphs.

    Args:
        fb2_path: FB2 file written by this program.

    Returns:
        Problem descriptions (empty when valid).
    """
    try:
        # B314/S314/use-defused-xml-parse: the FB2 file was generated by this program, not external input,
        # and the stdlib parser never resolves external entities.
        # nosemgrep: python.lang.security.use-defused-xml-parse.use-defused-xml-parse
        root_element = ElementTree.parse(fb2_path).getroot()  # nosec B314  # noqa: S314
    except ElementTree.ParseError as parse_error:
        return [f"FB2 is not well-formed XML: {parse_error}"]
    element_ids = [xml_element.get("id") for xml_element in root_element.iter() if xml_element.get("id")]
    fb2_problems = _find_duplicate_ids(element_ids) + _find_broken_links(root_element, set(element_ids))
    if not root_element.findall(f".//{{{FB2_NAMESPACE}}}body//{{{FB2_NAMESPACE}}}p"):
        fb2_problems.append("FB2 has no paragraphs")
    return fb2_problems
